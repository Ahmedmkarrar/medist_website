export interface SubCategory {
  id: string;
  name: string;
  products: string[];
}

export interface Industry {
  id: string;
  name: string;
  icon: string;
  color: string;
  lightBg: string;
  subcategories: SubCategory[];
  products: string[]; // flat list derived from subcategories
}

function makeIndustry(
  base: Omit<Industry, 'products'>,
): Industry {
  return { ...base, products: base.subcategories.flatMap(s => s.products) };
}

